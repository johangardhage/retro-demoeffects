//
// Mesh warp
//
// A portrait pulled around by a 10x9 grid of control points, moving from key
// to key of a scripted animation. When the last key has been held, it starts
// over.
//
// The source picture is cut by GRID_COLUMNS vertical and GRID_ROWS horizontal
// lines, plus the edges. Each key moves where those lines cross: a vertical
// line's x at each horizontal line, and a horizontal line's y at each vertical
// line. The edges stay put. Between crossings a line is interpolated, so every
// vertical line has an x on every screen row, and every horizontal line a y on
// every screen column.
//
// The warp is then two one-dimensional resamples. The first stretches each
// column so the source rows between two horizontal lines fill the screen rows
// between where they now are. The second stretches each row the same way
// between the vertical lines.
//
// The animation is a function of time, counted in ticks, TICKS_PER_SECOND to
// the second. A move between two keys takes KEY_TICKS ticks, and each key is
// then held for its own number of ticks. Along a move, the grid mixes the two
// keys by a smoothstep of the progress, so it starts and stops gently.
//
// The keys are given as how far each crossing has moved from where it is in
// the source picture. The first and last keys are the source picture itself,
// so the loop starts and ends on it.
//
// The picture is IMAGE_WIDTH x IMAGE_HEIGHT and is stretched to fill the
// screen: the crossings are scaled to it, and the second resample runs over
// the screen's rows.
//
// Author: Johan Gardhage <johan.gardhage@gmail.com>
//
