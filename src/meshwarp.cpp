// Where the lines cross: the vertical line's x and the horizontal line's y
static vec2 Grid[LINES_Y][LINES_X];
static unsigned char Intermediate[IMAGE_WIDTH * RETRO_HEIGHT]; // picture columns, screen rows

//
// The grid after tick ticks: the two keys it is between and how far along the
// eased move from one to the other
//
static void Animate(double tick)
{
	int loop = Keys[0].hold;
	for (int k = 1; k < KEYS; k++) {
		loop += KEY_TICKS + Keys[k].hold;
	}

	// Each key after the first is a move to it and then its hold
	double t = fmod(tick, loop) - Keys[0].hold;
	int to = 1;
	while (to < KEYS - 1 && t >= KEY_TICKS + Keys[to].hold) {
		t -= KEY_TICKS + Keys[to].hold;
		to++;
	}
	double amount = smoothstep(0.0, KEY_TICKS, t);
	for (int row = 0; row < LINES_Y; row++) {
		for (int col = 0; col < LINES_X; col++) {
			vec2 p = { (float)SourceX[col], (float)SourceY[row] };
			// The edges never move
			if (row > 0 && col > 0 && row < LINES_Y - 1 && col < LINES_X - 1) {
				p += mix(Keys[to - 1].move[row - 1][col - 1], Keys[to].move[row - 1][col - 1], amount);
			}
			Grid[row][col] = { p.x * RETRO_WIDTH / IMAGE_WIDTH, p.y * RETRO_HEIGHT / IMAGE_HEIGHT };
		}
	}
}

//
// Stretch a line of pixels, stride apart, segment by segment: the source
// between src[i - 1] and src[i] over the destination between dst[i - 1] and
// dst[i]
//
static void Resample(const unsigned char *in, unsigned char *out, int stride, const int *src, const int *dst, int lines, int size)
{
	for (int i = 1; i < lines; i++) {
		int span = src[i] - src[i - 1];
		for (int d = MAX(dst[i - 1], 0); d < MIN(dst[i], size); d++) {
			int s = src[i - 1] + (d - dst[i - 1]) * span / (dst[i] - dst[i - 1]);
			out[d * stride] = in[s * stride];
		}
	}
}

//
// The two resamples: each column between where the horizontal lines now cross
// it, then each row between where the vertical lines now cross it. A line
// between two crossings is interpolated
//
static void Warp(void)
{
	unsigned char *image = RETRO_ImageData();
	for (int col = 1; col < LINES_X; col++) {
		int left = SourceX[col - 1];
		int span = SourceX[col] - left;
		for (int j = 0; j < span; j++) {
			float t = (float)j / span;
			int lines[LINES_Y];
			for (int row = 0; row < LINES_Y; row++) {
				lines[row] = (int)floorf(mix(Grid[row][col - 1].y, Grid[row][col].y, t));
			}
			Resample(image + left + j, Intermediate + left + j, IMAGE_WIDTH, SourceY, lines, LINES_Y, RETRO_HEIGHT);
		}
	}

	unsigned char *screen = RETRO_FrameBuffer();
	for (int row = 1; row < LINES_Y; row++) {
		int top = SourceY[row - 1] * RETRO_HEIGHT / IMAGE_HEIGHT;
		int span = SourceY[row] * RETRO_HEIGHT / IMAGE_HEIGHT - top;
		for (int j = 0; j < span; j++) {
			float t = (float)j / span;
			int lines[LINES_X];
			for (int col = 0; col < LINES_X; col++) {
				lines[col] = (int)floorf(mix(Grid[row - 1][col].x, Grid[row][col].x, t));
			}
			int y = top + j;
			Resample(Intermediate + y * IMAGE_WIDTH, screen + y * RETRO_WIDTH, 1, SourceX, lines, LINES_X, RETRO_WIDTH);
		}
	}
}

void DEMO_Render(RETRO_Time time)
{
	Animate(time.total * TICKS_PER_SECOND);
	Warp();
}

